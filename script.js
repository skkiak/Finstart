        let currentUser = null;
        let myChart = null;

        function init() {
            const session = localStorage.getItem('finstart_session');
            if (session) { currentUser = JSON.parse(session); launch(); }
        }

        function toggleAuth(isReg) {
            document.getElementById('auth-reg-section').classList.toggle('hidden', !isReg);
            document.getElementById('auth-login-section').classList.toggle('hidden', isReg);
        }

        function showAuth() { document.getElementById('modal-auth').classList.remove('hidden'); }

        function handleRegister() {
            const name = document.getElementById('reg-name').value;
            const email = document.getElementById('reg-email').value.toLowerCase();
            const pass = document.getElementById('reg-pass').value;
            if(!name || !email || !pass) return alert("Заполни всё!");
            let users = JSON.parse(localStorage.getItem('finstart_users') || "[]");
            if(users.find(u => u.email === email)) return alert("Email занят!");
            currentUser = { name, email, pass, level: 1, completed: [], achievements: [] };
            users.push(currentUser);
            localStorage.setItem('finstart_users', JSON.stringify(users));
            localStorage.setItem('finstart_session', JSON.stringify(currentUser));
            launch();
        }

        function handleLogin() {
            const email = document.getElementById('login-email').value.toLowerCase();
            const pass = document.getElementById('login-pass').value;
            let users = JSON.parse(localStorage.getItem('finstart_users') || "[]");
            const user = users.find(u => u.email === email && u.pass === pass);
            if(!user) return alert("Ошибка входа!");
            currentUser = user;
            localStorage.setItem('finstart_session', JSON.stringify(currentUser));
            launch();
        }

        function handleLogout() { localStorage.removeItem('finstart_session'); location.reload(); }

        function launch() {
            document.getElementById('screen-landing').classList.add('hidden');
            document.getElementById('modal-auth').classList.add('hidden');
            document.getElementById('screen-app').style.display = 'flex';
            document.getElementById('u-name').innerText = currentUser.name;
            document.getElementById('u-avatar').src = `https://api.dicebear.com/7.x/bottts/svg?seed=${currentUser.name}`;
            updateUI(); recalc();
        }

        function saveProgress() {
            localStorage.setItem('finstart_session', JSON.stringify(currentUser));
            let users = JSON.parse(localStorage.getItem('finstart_users') || "[]");
            const idx = users.findIndex(u => u.email === currentUser.email);
            if(idx !== -1) { users[idx] = currentUser; localStorage.setItem('finstart_users', JSON.stringify(users)); }
        }

        function switchTab(t) {
            document.querySelectorAll('.content-section').forEach(s => s.classList.remove('active'));
            document.querySelectorAll('.menu-item').forEach(m => m.classList.remove('active'));
            document.getElementById(`tab-${t}`).classList.add('active');
            if(document.getElementById(`m-${t}`)) document.getElementById(`m-${t}`).classList.add('active');
            if(t === 'lessons') renderLessons();
            if(t === 'ach') renderAch();
        }

        function renderLessons() {
            const c = document.getElementById('lessons-list'); c.innerHTML = '';
            LESSONS_DATA.forEach(l => {
                const isDone = currentUser.completed.includes(l.id);
                c.innerHTML += `<div class="lesson-item ${isDone?'completed':''}" onclick="openLesson(${l.id})">
                    <div class="lesson-icon-box"><i class="ph-bold ${l.icon}"></i></div>
                    <div style="flex:1"><h4>Урок ${l.id}. ${l.title}</h4><p>${isDone?'Завершен ✅':'Начать'}</p></div>
                </div>`;
            });
        }

        function openLesson(id) {
            const l = LESSONS_DATA.find(x => x.id === id);
            switchTab('lesson-view');
            document.getElementById('lesson-full-content').innerHTML = `
                <h2>${l.title}</h2><div class="lesson-body">${l.content}</div>
                <div class="test-box"><h3>Тест: ${l.test.q}</h3>
                <div class="test-options">${l.test.a.map((opt, i) => `<button class="option-btn" style="padding:12px" onclick="checkAnswer(${id},${i})">${opt}</button>`).join('')}</div></div>`;
        }

        function checkAnswer(id, idx) {
            const l = LESSONS_DATA.find(x => x.id === id);
            if(idx === l.test.correct) {
                if(!currentUser.completed.includes(id)) {
                    currentUser.completed.push(id);
                    checkAchievements();
                    saveProgress();
                    alert("Правильно!");
                }
                switchTab('lessons');
                updateUI();
            } else alert("Попробуй еще раз!");
        }

        function checkAchievements() {
            if(currentUser.completed.length >= 1 && !currentUser.achievements.includes('start')) currentUser.achievements.push('start');
            if(currentUser.completed.includes(14) && currentUser.completed.includes(15) && !currentUser.achievements.includes('investor')) currentUser.achievements.push('investor');
            if(currentUser.completed.length === 19 && !currentUser.achievements.includes('pro')) currentUser.achievements.push('pro');
        }

        function renderAch() {
            const c = document.getElementById('ach-container'); c.innerHTML = '';
            ACHIEVEMENTS_DATA.forEach(a => {
                const got = currentUser.achievements.includes(a.id);
                c.innerHTML += `<div class="ach-card ${got?'unlocked':''}">
                    <span class="ach-icon">${a.icon}</span><h4>${a.title}</h4><p style="font-size:0.7rem">${a.desc}</p>
                </div>`;
            });
        }

        function recalc() {
            const i = +document.getElementById('val-income').value || 0;
            const e = +document.getElementById('val-expense').value || 0;
            const d = i - e;
            const score = i > 0 ? Math.round((d/i)*100) : 0;
            
            // Логика цвета круга ФинСкора
            const circle = document.getElementById('score-circle');
            const msg = document.getElementById('score-msg');
            const num = document.getElementById('score-num');

            num.innerText = Math.max(0, score);
            
            // Сброс классов
            circle.classList.remove('score-low', 'score-med', 'score-high');
            
            if(score >= 50) {
                circle.classList.add('score-high');
                msg.innerText = "Отличный результат! 🚀";
                msg.style.color = "var(--s)";
            } else if(score >= 20) {
                circle.classList.add('score-med');
                msg.innerText = "Неплохо, но есть риски 😐";
                msg.style.color = "var(--warn)";
            } else {
                circle.classList.add('score-low');
                msg.innerText = "Опасно! Расходы слишком высоки 🚨";
                msg.style.color = "var(--danger)";
            }

            if(score > 70 && !currentUser.achievements.includes('saver')) { currentUser.achievements.push('saver'); saveProgress(); }
            renderChart(d);
        }

        function renderChart(d) {
            const ctx = document.getElementById('financeChart').getContext('2d');
            if(myChart) myChart.destroy();
            myChart = new Chart(ctx, {
                type: 'line',
                data: { labels: ['Янв','Фев','Мар','Апр','Май','Июн'], datasets: [{ label: 'Капитал (KGZ)', data: [d, d*2, d*3, d*4, d*5, d*6], borderColor: '#4F46E5', fill: true }] }
            });
        }

        function updateUI() {
            document.getElementById('u-level').innerText = Math.floor(currentUser.completed.length / 4) + 1;
        }

